import { useState, useEffect } from 'react';
import { useParams, useNavigate } from 'react-router-dom';
import QRCode from 'qrcode';
import { ArrowLeft, Printer, Ban } from 'lucide-react';
import { apiClient } from '../api/client';
import { Loading, toast, fmtDate, getUser } from '../components/ui';

export default function Letter() {
  const { id } = useParams();
  const navigate = useNavigate();
  const [l, setL] = useState(null);
  const [qr, setQr] = useState('');
  const verifyUrl = l ? `${window.location.origin}/verify/${l.letter_code}` : '';

  const load = () => apiClient.get(`/applications/${id}/letter`).then(setL).catch(e => { toast(e.message, 'error'); navigate(-1); });
  useEffect(() => { load(); }, [id]);
  const revoke = async () => {
    const reason = window.prompt('Reason for revoking this letter (shown publicly on the verification page):');
    if (!reason) return;
    try { await apiClient.post(`/applications/${id}/letter/revoke`, { reason }); toast('Letter revoked; verification page updated'); load(); } catch (e) { toast(e.message, 'error'); }
  };
  useEffect(() => { if (verifyUrl) QRCode.toDataURL(verifyUrl, { margin: 1, width: 132 }).then(setQr).catch(() => {}); }, [verifyUrl]);
  if (!l) return <Loading />;

  const rejected = l.status === 'Rejected';
  const conditional = l.status === 'Conditionally Approved';
  const title = rejected ? 'Letter of Rejection (LoR)' : conditional ? 'Letter of Approval — Conditional (LoA)' : 'Letter of Approval (LoA)';

  return (
    <div>
      <div className="sl-flex sl-justify-between sl-mb-4 aq-noprint">
        <button className="sl-btn sl-btn--ghost sl-btn--sm" onClick={() => navigate(-1)}><ArrowLeft size={14} /> Back</button>
        <div className="sl-flex sl-gap-2">
          {getUser().role === 'Admin' && !l.letter_revoked_at && <button className="sl-btn sl-btn--danger" onClick={revoke}><Ban size={16} /> Revoke letter</button>}
          <button className="sl-btn sl-btn--primary" onClick={() => window.print()}><Printer size={16} /> Print / Save PDF</button>
        </div>
      </div>
      {l.letter_revoked_at && <div className="aq-panel sl-mb-4 sl-text-danger aq-noprint" style={{ borderColor: 'var(--sl-danger)' }}><b>Revoked on {fmtDate(l.letter_revoked_at)}:</b> {l.letter_revoke_reason}. The public verification page shows this letter as revoked.</div>}
      <div className="aq-letter" style={l.letter_revoked_at ? { opacity: 0.55 } : undefined}>
        <div className="aq-letter__head">
          <div>
            <div style={{ fontSize: 13, letterSpacing: 1, color: '#1e3a8a', fontWeight: 700 }}>ALL INDIA COUNCIL FOR TECHNICAL EDUCATION</div>
            <div style={{ fontSize: 12, color: '#444' }}>Approval Bureau · {l.institution.region.name}, {l.institution.region.city}</div>
            <div style={{ fontSize: 11, color: '#b91c1c', marginTop: 4 }}>SPECIMEN generated by the SiteLine SIH prototype — not an official document</div>
          </div>
          <div style={{ textAlign: 'right', fontSize: 12 }}>
            {qr && <img src={qr} alt="Verification QR code" width={96} height={96} />}
            <div>Verify: <b>{l.letter_code}</b></div>
          </div>
        </div>
        <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: 14 }}><span>Ref: {l.app_number}</span><span>Date: {fmtDate(l.decided_at)}</span></div>
        <p style={{ marginTop: 18 }}>To,<br />The Principal / Director<br /><b>{l.institution.name}</b><br />{l.institution.city}, {l.institution.state}<br />AICTE Permanent ID: {l.institution.aicte_id}</p>
        <h2 style={{ textAlign: 'center', fontSize: 18, margin: '20px 0' }}>{title}</h2>
        <p>Subject: {l.type} for the Academic Year {l.academic_year}.</p>
        {rejected ? (
          <p>With reference to the application cited above, the Council, after Scrutiny, Expert Visit and consideration by the Executive Committee, regrets to inform that the application has <b>not been approved</b> on the following grounds: <i>{l.decision_remarks || 'Non-compliance with the norms prescribed in the Approval Process Handbook.'}</i> The institution may file an appeal before the Standing Appellate Committee (SAC) within 30 days of this letter.</p>
        ) : (
          <p>With reference to the application cited above, the Council, after due process under the Approval Process Handbook (Scrutiny{l.transitions.some(t => t.to_stage === 'EVC') ? ', Expert Visit Committee' : ''} and Executive Committee), is pleased to grant approval for <b>{l.type}</b>{l.intake_requested ? ` with intake of ${l.intake_requested}` : ''}{l.courses ? ` for ${l.courses}` : ''} for the Academic Year {l.academic_year}{conditional ? ', subject to the time-bound undertakings listed below' : ''}.</p>
        )}
        {conditional && l.undertakings.length > 0 && (
          <>
            <p>The institution shall comply with the following and upload evidence on the portal before the due date, failing which action may be initiated as per the APH:</p>
            <table><thead><tr><th>#</th><th>Undertaking</th><th>Category</th><th>Due date</th></tr></thead>
              <tbody>{l.undertakings.map((u, i) => <tr key={u.id}><td>{i + 1}</td><td>{u.title}</td><td>{u.category}</td><td>{fmtDate(u.due_date)}</td></tr>)}</tbody></table>
          </>
        )}
        <p>Processing summary: submitted {fmtDate(l.submitted_at)}, decided {fmtDate(l.decided_at)} ({l.total_days} days).</p>
        <p style={{ marginTop: 40 }}>Yours faithfully,<br /><br /><b>Director, Approval Bureau</b><br /><span style={{ fontSize: 12, color: '#555' }}>Digitally generated. Authenticity can be verified at {verifyUrl}</span></p>
      </div>
    </div>
  );
}
